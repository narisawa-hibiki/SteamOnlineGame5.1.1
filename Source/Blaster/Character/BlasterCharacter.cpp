	TurningInPlace = ETurningInPlace::ETIP_NotTurning;
	// ネットワーク更新頻度の設定
	NetUpdateFrequency = 66.f;
	MinNetUpdateFrequency = 33.f;

	// ディゾルブタイムラインの作成
	DissolveTimeline = CreateDefaultSubobject<UTimelineComponent>(TEXT("DissolveTimelineComponent"));

	// アタッチされたグレネードメッシュの作成
